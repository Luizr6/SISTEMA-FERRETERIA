-- Única tabla propia del microservicio. Django no la conoce ni la modifica.
-- Se ejecuta en cada arranque; IF NOT EXISTS la hace segura.
CREATE TABLE IF NOT EXISTS ms_evento_auditoria (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha        TIMESTAMP WITH TIME ZONE NOT NULL,
    tipo         VARCHAR(40)  NOT NULL,
    nivel        VARCHAR(12)  NOT NULL,
    origen       VARCHAR(20)  NOT NULL,
    modulo       VARCHAR(40),
    usuario      VARCHAR(150),
    usuario_id   BIGINT,
    entidad      VARCHAR(60),
    entidad_id   VARCHAR(40),
    descripcion  VARCHAR(500) NOT NULL,
    datos        TEXT,
    ip           VARCHAR(45)
);

CREATE INDEX IF NOT EXISTS ix_ms_evento_fecha ON ms_evento_auditoria (fecha DESC);
CREATE INDEX IF NOT EXISTS ix_ms_evento_tipo_usuario ON ms_evento_auditoria (tipo, usuario, fecha);
