-- Tablas propias del microservicio (prefijo ms_). Django no las conoce ni las modifica.
-- Se ejecuta en cada arranque; IF NOT EXISTS lo hace seguro.

-- Auditoría independiente
CREATE TABLE IF NOT EXISTS ms_evento_auditoria (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha        TIMESTAMP WITH TIME ZONE NOT NULL,
    tipo         VARCHAR(40)  NOT NULL,
    nivel        VARCHAR(12)  NOT NULL,
    origen       VARCHAR(20)  NOT NULL,
    modulo       VARCHAR(40),
    usuario      VARCHAR(150),
    usuario_id   BIGINT,
    entidad      VARCHAR(60),
    entidad_id   VARCHAR(40),
    descripcion  VARCHAR(500) NOT NULL,
    datos        TEXT,
    ip           VARCHAR(45)
);

CREATE INDEX IF NOT EXISTS ix_ms_evento_fecha ON ms_evento_auditoria (fecha DESC);
CREATE INDEX IF NOT EXISTS ix_ms_evento_tipo_usuario ON ms_evento_auditoria (tipo, usuario, fecha);

-- Comprobantes electrónicos (simulados) que emite el microservicio a partir de las ventas de Django.
CREATE TABLE IF NOT EXISTS ms_comprobante (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id          BIGINT        NOT NULL UNIQUE,
    tipo              VARCHAR(10)   NOT NULL,
    codigo_tipo       VARCHAR(2)    NOT NULL,
    serie             VARCHAR(4)    NOT NULL,
    correlativo       INTEGER       NOT NULL,
    numero            VARCHAR(20)   NOT NULL,
    fecha_emision     TIMESTAMP WITH TIME ZONE NOT NULL,
    cliente_tipo_doc  VARCHAR(1)    NOT NULL,
    cliente_documento VARCHAR(20)   NOT NULL,
    cliente_nombre    VARCHAR(150)  NOT NULL,
    op_gravada        NUMERIC(12,2) NOT NULL,
    igv               NUMERIC(12,2) NOT NULL,
    total             NUMERIC(12,2) NOT NULL,
    hash              VARCHAR(64)   NOT NULL,
    xml               TEXT          NOT NULL,
    estado            VARCHAR(10)   NOT NULL,
    fecha_anulacion   TIMESTAMP WITH TIME ZONE,
    motivo_anulacion  VARCHAR(250),
    generado_en       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_ms_comprobante_numero UNIQUE (serie, correlativo)
);

CREATE INDEX IF NOT EXISTS ix_ms_comprobante_fecha ON ms_comprobante (fecha_emision DESC);

-- Cierre del día (tarea programada de las 23:00 o ejecución manual del Administrador).
CREATE TABLE IF NOT EXISTS ms_cierre_diario (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha                 DATE          NOT NULL UNIQUE,
    cantidad_ventas       BIGINT        NOT NULL,
    ventas_anuladas       BIGINT        NOT NULL,
    total_vendido         NUMERIC(12,2) NOT NULL,
    ticket_promedio       NUMERIC(12,2) NOT NULL,
    total_efectivo        NUMERIC(12,2) NOT NULL,
    total_otros_medios    NUMERIC(12,2) NOT NULL,
    comprobantes_emitidos BIGINT        NOT NULL,
    cajas_cerradas        BIGINT        NOT NULL,
    cajas_abiertas        BIGINT        NOT NULL,
    faltantes             NUMERIC(12,2) NOT NULL,
    sobrantes             NUMERIC(12,2) NOT NULL,
    productos_criticos    BIGINT        NOT NULL,
    alertas               TEXT,
    origen                VARCHAR(12)   NOT NULL,
    generado_en           TIMESTAMP WITH TIME ZONE NOT NULL
);
